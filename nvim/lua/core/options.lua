local opt = vim.opt

-- line numbers
opt.number = true
opt.relativenumber = true


-- mouse
opt.mouse = "a"

-- Clipboard
opt.clipboard = "unnamedplus"

-- Colors
opt.termguicolors = true

-- Tabs & indentation
opt.tabstop = 4
opt.shiftwidth = 4
opt.expandtab = true

-- Keep space around cursor (feels smoother)
opt.scrolloff = 8
opt.sidescrolloff = 8

opt.signcolumn = "yes"
